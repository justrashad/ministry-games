"""usage: python3 tools/packs/build.py

Generates every title's server pack files from the era sources (era1.py ... era4.py)."""
import importlib, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from books import es_ref

REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
RELEASED = '2026-11-15'
NAMES = {
 'eden-to-egypt': (('From Eden to Egypt', 'Genesis: creation, Noah, Abraham, Jacob and Joseph.'), ('Del Edén a Egipto', 'Génesis: la creación, Noé, Abrahán, Jacob y José.')),
 'exodus-to-judges': (('Exodus to the Judges', 'Moses, the wilderness, Joshua, the judges and Ruth.'), ('Del Éxodo a los Jueces', 'Moisés, el desierto, Josué, los jueces y Rut.')),
 'kings-and-prophets': (('Kings and Prophets', 'Samuel, David, Solomon, Elijah, Esther, Daniel and more.'), ('Reyes y profetas', 'Samuel, David, Salomón, Elías, Ester, Daniel y más.')),
 'jesus-and-early-christians': (('Jesus and the Early Christians', 'The life of Jesus, the apostles and the congregation in Acts.'), ('Jesús y los primeros cristianos', 'La vida de Jesús, los apóstoles y la congregación en Hechos.')),
}
POINTS = {1: [100], 2: [60, 40], 3: [40, 32, 28], 4: [34, 28, 22, 16], 5: [30, 25, 20, 15, 10], 6: [28, 22, 18, 14, 10, 8], 7: [26, 20, 16, 12, 10, 8, 8]}

def eras():
    out = []
    for n in range(1, 5):
        if os.path.exists(os.path.join(HERE, f'era{n}.py')):
            out.append(importlib.import_module(f'era{n}'))
    return out

def clue(id_, cat, lv, prompt, answer, ref, accept):
    o = {'id': id_, 'type': 'clue', 'category': cat, 'level': lv, 'prompt': prompt, 'answer': answer}
    if ref: o['reference'] = ref
    if accept: o['accept'] = accept
    return o

def theo(m):
    code = m.PACK['code']; en, es = [], []
    for ci, (ce, cs, rows) in enumerate(m.THEO, 1):
        for lv, qe, ae, xe, qs, as_, xs, ref, _ in rows:
            i = f'{code}-c{ci:02d}-{lv}'
            en.append(clue(i, ce, lv, qe, ae, ref, xe)); es.append(clue(i, cs, lv, qs, as_, es_ref(ref), xs))
    for fi, (qe, ae, xe, qs, as_, xs, ref, _) in enumerate(m.THEO_FINALS, 1):
        i = f'{code}-final-{fi}'
        en.append(clue(i, 'Final Round', 5, qe, ae, ref, xe)); es.append(clue(i, 'Ronda final', 5, qs, as_, es_ref(ref), xs))
    return en, es

def squares(m):
    code = m.PACK['code']; en, es = [], []
    for ci, (ce, cs, rows) in enumerate(m.KS, 1):
        for si, (lv, se, t, cre, ss, crs, ref, _) in enumerate(rows, 1):
            i = f'{code}-ks{ci}-{si:02d}'
            e = {'id': i, 'type': 'truefalse', 'category': ce, 'level': lv, 'statement': se, 'isTrue': t, 'reference': ref}
            s = {'id': i, 'type': 'truefalse', 'category': cs, 'level': lv, 'statement': ss, 'isTrue': t, 'reference': es_ref(ref)}
            if not t: e['correction'] = cre; s['correction'] = crs
            en.append(e); es.append(s)
    return en, es

def babe(m):
    code = m.PACK['code']; en, es = [], []; count = {}
    for lv, subj, qe, ae, xe, qs, as_, xs, ref, _ in m.BABE:
        count[lv] = count.get(lv, 0) + 1
        i = f'{code}-sb{lv}-{count[lv]:02d}'
        se, ss = m.BABE_SUBJECTS[subj]
        en.append(clue(i, se, lv, qe, ae, ref, xe)); es.append(clue(i, ss, lv, qs, as_, es_ref(ref), xs))
    for bi, (qe, ae, xe, qs, as_, xs, ref, _) in enumerate(m.BABE_BONUS, 1):
        i = f'{code}-bonus-{bi}'
        se, ss = m.BABE_SUBJECTS['BONUS']
        en.append(clue(i, se, 5, qe, ae, ref, xe)); es.append(clue(i, ss, 5, qs, as_, es_ref(ref), xs))
    return en, es

def showdown(m):
    code = m.PACK['code']; en, es = [], []
    for n, (cat, qe, ae, qs, as_, ref, fl) in enumerate(m.MS, 1):
        assert len(ae) == len(as_), qe
        pts = POINTS[len(ae)]
        for lang, out, cat_name, text, answers, r, pre in (('en', en, m.MS_CATS[cat][0], qe, ae, ref, f'pk-{code}'), ('es', es, m.MS_CATS[cat][1], qs, as_, es_ref(ref), f'pk-es-{code}')):
            i = f'{pre}-{n:02d}'
            o = {'id': i, 'category': cat_name, 'question': text,
                 'answers': [{'id': f'{i}-a{k + 1}', 'text': a, 'points': p} for k, (a, p) in enumerate(zip(answers, pts))],
                 'notes': ('See ' if lang == 'en' else 'Vea ') + r + '.'}
            if fl.get('final'): o['isFinalRound'] = True
            if fl.get('fc'): o['isFinalChallenge'] = True
            out.append(o)
    return en, es

HEAD = '''/*
 * GENERATED by tools/packs/build.py from the era sources. Do not edit by hand.
 * PAID CONTENT: bundled only into the Netlify Function, never into the public website.
 * Every answer was checked against the New World Translation (English and Spanish) on jw.org.
 */
'''

def ts(obj):
    return json.dumps(obj, ensure_ascii=False, indent=2)

def write(path, typ_import, qtype, build):
    packs, es = [], {}
    for m in eras():
        pid = m.PACK['id']; (ne, de), (ns, ds) = NAMES[pid]
        qe, qs = build(m)
        packs.append({'id': pid, 'name': ne, 'description': de, 'released': RELEASED, 'questions': qe})
        es[pid] = {'name': ns, 'description': ds, 'questions': qs}
    body = HEAD + typ_import + f"\nexport const PACKS: PackDef<{qtype}>[] = {ts(packs)};\n\nexport const PACKS_ES: Record<string, TranslatedPack<{qtype}>> = {ts(es)};\n"
    open(f'{REPO}/{path}', 'w').write(body)
    print(path, [len(p['questions']) for p in packs])

LIC = "import type { PackDef, TranslatedPack } from '../core/licensing';\n"
write('server/theopardy/packs.ts', LIC + "import type { ClueQuestion } from '../../src/core/questions/types';\n", 'ClueQuestion', theo)
write('server/squares/packs.ts', LIC + "import type { TrueFalseQuestion } from '../../src/core/questions/types';\n", 'TrueFalseQuestion', squares)
write('server/babe/packs.ts', LIC + "import type { ClueQuestion } from '../../src/core/questions/types';\n", 'ClueQuestion', babe)

# Ministry Showdown keeps its own pack shapes.
packs, es = [], {}
for m in eras():
    pid = m.PACK['id']; (ne, de), (ns, ds) = NAMES[pid]
    qe, qs = showdown(m)
    packs.append({'id': pid, 'name': ne, 'description': de, 'released': RELEASED, 'questions': qe})
    es[pid] = {'name': ns, 'description': ds, 'questions': qs}
open(f'{REPO}/server/showdown/eraPacks.ts', 'w').write(HEAD + "import type { Question } from '../../src/games/showdown/types';\n\n"
    f"export const ERA_PACKS: {{ id: string; name: string; description: string; released: string; questions: Question[] }}[] = {ts(packs)};\n\n"
    f"export const ERA_PACKS_ES: Record<string, {{ name: string; description: string; questions: Question[] }}> = {ts(es)};\n")
print('server/showdown/eraPacks.ts', [len(p['questions']) for p in packs])
